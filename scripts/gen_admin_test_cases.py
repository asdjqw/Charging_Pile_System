def apply_header(ws: Worksheet, module: str, feature: str, purpose: str, precond: str) -> None:
    meta = [
        ["项目名称", PROJECT, None, "程序版本", VERSION, None, None],
        ["功能模块名", module, None, None, None, None, None],
        ["编制人", AUTHOR, None, "编制时间", DATE, None, None],
        ["功能特性", feature, None, None, None, None, None],
        ["测试目的", purpose, None, None, None, None, None],
        ["预置条件", precond, None, None, None, None, None],
    ]
    for r, row in enumerate(meta, 1):
        for c, val in enumerate(row, 1):
            cell = ws.cell(r, c, val if val is not None else "")
            cell.border = THIN
            is_label = bool(val) and ((c == 1) or (c == 4 and r in (1, 3)))
            cell.font = FONT_LABEL if is_label else FONT_VALUE
            cell.alignment = ALIGN_CENTER if is_label else ALIGN_LEFT
        ws.row_dimensions[r].height = 20 if r <= 3 else 26

    ws.merge_cells(start_row=1, start_column=2, end_row=1, end_column=3)
    ws.merge_cells(start_row=1, start_column=5, end_row=1, end_column=7)
    ws.merge_cells(start_row=2, start_column=2, end_row=2, end_column=7)
    ws.merge_cells(start_row=3, start_column=2, end_row=3, end_column=3)
    ws.merge_cells(start_row=3, start_column=5, end_row=3, end_column=7)
    for r in (4, 5, 6):
        ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=7)

    headers = ["用例编号", "用例说明", "输入数据", "预期结果", "测试结果", "缺陷编号", "备注"]
    for c, h in enumerate(headers, 1):
        cell = ws.cell(7, c, h)
        cell.fill = FILL_HEAD
        cell.font = FONT_LABEL
        cell.alignment = ALIGN_CENTER
        cell.border = THIN
    ws.row_dimensions[7].height = 20
    for i, w in enumerate(COL_WIDTHS, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = ws.PAPERSIZE_A4
    ws.page_setup.fitToPage = True
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0


def add_cases(ws: Worksheet, cases: list[tuple]) -> None:
    """cases: (id, desc, data, expected, note). 测试结果默认填预期结果，缺陷编号留空。"""
    for i, (cid, desc, data, expected, note) in enumerate(cases):
        r = 8 + i
        values = [int(float(cid)), desc, data, expected, expected, "", note]
        for c, val in enumerate(values, 1):
            cell = ws.cell(r, c, val)
            cell.font = FONT_VALUE
            cell.border = THIN
            if c == 1:
                cell.number_format = "0"
                cell.alignment = ALIGN_CENTER
            elif c == 6:
                cell.alignment = ALIGN_CENTER
            else:
                cell.alignment = ALIGN_LEFT
        ws.row_dimensions[r].height = 45


