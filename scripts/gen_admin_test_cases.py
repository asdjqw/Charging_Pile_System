    wb = Workbook()
    wb.remove(wb.active)
    for name, module, feature, purpose, precond, cases in MODULES:
        ws = wb.create_sheet(name)
        apply_header(ws, module, feature, purpose, precond)
        add_cases(ws, cases)
    wb.save(OUT)
    print("wrote", OUT, "sheets", len(MODULES))


